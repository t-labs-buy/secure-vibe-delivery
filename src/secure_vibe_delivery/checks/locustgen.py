"""Generate a starter locustfile: OpenAPI spec → framework route scan → GET /."""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Optional

import httpx
import yaml

from ..detect import iter_files

ROUTE_PATTERNS = [
    # FastAPI / APIRouter / Flask 2 shortcuts:  @app.get("/x")  @router.get('/x')
    re.compile(r"@\w+\.(get)\(\s*['\"]([^'\"]+)['\"]"),
    # Flask classic: @app.route("/x") or methods=["GET"]
    re.compile(r"@\w+\.route\(\s*['\"]([^'\"]+)['\"](?![^)]*methods\s*=\s*\[[^\]]*['\"](?:POST|PUT|DELETE|PATCH)['\"][^\]]*\])"),
    # Express / Koa / Fastify:  app.get('/x', ...)  router.get("/x", ...)
    re.compile(r"\b(?:app|router|server|api)\.(get)\(\s*['\"`]([^'\"`]+)['\"`]"),
]
SKIP_PATHS = re.compile(r"^/(docs|redoc|openapi\.json|swagger|static|favicon|metrics)", re.I)
HEADER = '''"""Generated by secure-vibe-delivery ({source}).

Review before relying on it: replace these journeys with the 3-5 things real users do most.
The number in @task(n) is a weight. Endpoints that need path parameters or a request body
are listed at the bottom as TODOs.

Optional login: set SVD_LOAD_LOGIN_PATH, SVD_LOAD_USER and SVD_LOAD_PASSWORD in the environment.
"""
import os

from locust import HttpUser, between, task


class GeneratedUser(HttpUser):
    wait_time = between(1, 3)  # pause like a real person between clicks

    def on_start(self):
        path = os.environ.get("SVD_LOAD_LOGIN_PATH")
        if path:
            self.client.post(path, json={{"username": os.environ.get("SVD_LOAD_USER", ""),
                                         "password": os.environ.get("SVD_LOAD_PASSWORD", "")}})
'''


def _task_name(path: str, used: set[str]) -> str:
    base = re.sub(r"[^a-zA-Z0-9]+", "_", path).strip("_").lower() or "home"
    if base[0].isdigit():
        base = "p_" + base
    name, i = base, 2
    while name in used:
        name, i = f"{base}_{i}", i + 1
    used.add(name)
    return name


def _weight(path: str) -> int:
    last = path.rstrip("/").rsplit("/", 1)[-1]
    if path == "/":
        return 2
    return 3 if last.endswith("s") or last in ("search", "list", "feed", "catalog") else 1


def from_openapi(spec: dict) -> tuple[list[str], list[str]]:
    gets, todos = [], []
    base = ""
    servers = spec.get("servers") or []
    if servers and isinstance(servers[0], dict):
        m = re.match(r"^(?:https?://[^/]+)?(/.*)?$", servers[0].get("url", ""))
        base = (m.group(1) or "").rstrip("/") if m else ""
    for path, ops in (spec.get("paths") or {}).items():
        if not isinstance(ops, dict):
            continue
        full = base + path
        for method in ops:
            if method.lower() not in ("get", "post", "put", "patch", "delete"):
                continue
            if method.lower() == "get" and "{" not in path and not SKIP_PATHS.match(full):
                params = ops[method].get("parameters", []) if isinstance(ops[method], dict) else []
                required_q = [p for p in params if isinstance(p, dict) and p.get("required") and p.get("in") == "query"]
                if not required_q:
                    gets.append(full)
                    continue
            todos.append(f"{method.upper()} {full}")
    return gets, todos


def from_routes(root: Path) -> list[str]:
    paths: list[str] = []
    for f in iter_files(root, (".py", ".js", ".ts", ".mjs", ".cjs"), limit=3000):
        if "test" in f.name or f.name == "locustfile.py":
            continue
        try:
            text = f.read_text(errors="ignore")
        except OSError:
            continue
        for pat in ROUTE_PATTERNS:
            for m in pat.finditer(text):
                p = m.groups()[-1]
                if p.startswith("/") and not re.search(r"[{<:*]", p) and not SKIP_PATHS.match(p) and p not in paths:
                    paths.append(p)
    return paths


def _load_spec(path: Path) -> Optional[dict]:
    try:
        text = path.read_text()
        return json.loads(text) if path.suffix == ".json" else yaml.safe_load(text)
    except Exception:
        return None


def generate(root: Path, target_url: Optional[str], openapi_file: Optional[Path]) -> tuple[str, str]:
    """Returns (locustfile source, how it was derived)."""
    gets, todos, source = [], [], ""
    spec = _load_spec(openapi_file) if openapi_file else None
    if spec is None and target_url:
        for candidate in ("/openapi.json", "/swagger.json", "/v3/api-docs", "/api/openapi.json"):
            try:
                r = httpx.get(target_url.rstrip("/") + candidate, timeout=5, follow_redirects=True)
                if r.status_code == 200 and "paths" in r.text[:200000]:
                    spec = r.json()
                    source = f"OpenAPI spec at {candidate}"
                    break
            except (httpx.HTTPError, ValueError):
                continue
    if spec:
        gets, todos = from_openapi(spec)
        source = source or f"OpenAPI spec {openapi_file.name if openapi_file else ''}".strip()
    if not gets:
        gets = from_routes(root)
        if gets:
            source = "routes found in the source code"
    if not gets:
        gets, source = ["/"], "fallback: home page only"
    gets = gets[:12]
    used: set[str] = set()
    body = [HEADER.format(source=source)]
    for p in gets:
        body.append(f"    @task({_weight(p)})\n    def {_task_name(p, used)}(self):\n"
                    f"        self.client.get({p!r})\n")
    if todos:
        body.append("\n# TODO: journeys that need parameters or a body (add them as tasks):\n")
        body += [f"#   {t}\n" for t in todos[:40]]
    return "\n".join(body), source
